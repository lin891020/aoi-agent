def core_path() -> list[Slide]:
    """The nine-slide ten-minute line, in the order they are told."""
    return sorted((s for s in SLIDES if s.core), key=lambda s: s.core)


def by_layer() -> dict[str, list[Slide]]:
    out: dict[str, list[Slide]] = {name: [] for name in LAYERS}
    for slide in SLIDES:
        out[slide.layer].append(slide)
    return out
